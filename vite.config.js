import { createHash } from 'crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'fs';
import { basename, dirname, join, resolve } from 'path';
import { defineConfig } from 'vite';

const copy = (source, target, filter = () => true) => {
  if (!existsSync(source)) {
    console.warn(`Source does not exist: ${source}`);
    return;
  }

  const stat = statSync(source);

  if (stat.isDirectory()) {
    if (!existsSync(target)) {
      mkdirSync(target, { recursive: true });
    }

    for (const entry of readdirSync(source)) {
      if (entry === '.DS_Store') continue;
      copy(join(source, entry), join(target, entry), filter);
    }
  } else if (filter(basename(source))) {
    const targetDir = dirname(target);
    if (!existsSync(targetDir)) {
      mkdirSync(targetDir, { recursive: true });
    }
    copyFileSync(source, target);
  }
};

// Plugin to copy all required assets (fonts and sass sources)
const copyAssetsPlugin = () => {
  return {
    name: 'copy-assets',
    writeBundle() {
      const nodeModules = resolve(import.meta.dirname, 'node_modules');
      const sassDir = resolve(import.meta.dirname, '_sass');
      const cssDir = resolve(import.meta.dirname, '_css');
      const webfontsDir = resolve(import.meta.dirname, 'assets/webfonts');

      // Font files (woff/woff2), for sites using the icon font themselves
      copy(
        join(nodeModules, 'bootstrap-icons/font/fonts'),
        webfontsDir,
        (file) => file.endsWith('.woff') || file.endsWith('.woff2')
      );

      // Sass files from _css
      for (const file of ['bootstrap.scss', 'theme.scss']) {
        copy(join(cssDir, file), join(sassDir, file));
      }
      copy(join(cssDir, 'main.scss'), join(sassDir, 'conference.scss'));

      // Bootstrap SCSS
      copy(
        join(nodeModules, 'bootstrap/scss'),
        join(sassDir, 'bootstrap/scss'),
        (file) => file.endsWith('.scss')
      );

      // Bootstrap Icons SCSS/CSS
      copy(
        join(nodeModules, 'bootstrap-icons/font'),
        join(sassDir, 'bootstrap-icons/font'),
        (file) => file.endsWith('.scss') || file.endsWith('.css')
      );

      // Leaflet CSS files
      copy(
        join(nodeModules, 'leaflet/dist/leaflet.css'),
        join(sassDir, 'leaflet/dist/leaflet.css')
      );
      copy(
        join(nodeModules, 'leaflet-easybutton/src/easy-button.css'),
        join(sassDir, 'leaflet-easybutton/src/easy-button.css')
      );
      copy(
        join(nodeModules, 'leaflet.locatecontrol/dist/L.Control.Locate.css'),
        join(sassDir, 'leaflet.locatecontrol/dist/L.Control.Locate.css')
      );

      console.log('Assets copied successfully');
    },
  };
};

// Inline SVG icons: each Bootstrap Icon becomes an include rendered at build
// time (see _includes/icon.html), e.g. icons/clock.svg; _names.txt lists all
// names (",alarm,alarm-fill,...,") so unknown names can be skipped
const iconsPlugin = () => {
  return {
    name: 'icons',
    writeBundle() {
      const source = resolve(import.meta.dirname, 'node_modules/bootstrap-icons/icons');
      const target = resolve(import.meta.dirname, '_includes/icons');
      rmSync(target, { recursive: true, force: true });
      mkdirSync(target, { recursive: true });

      const names = [];
      for (const file of readdirSync(source).filter((file) => file.endsWith('.svg'))) {
        const name = basename(file, '.svg');
        const svg = readFileSync(join(source, file), 'utf8')
          .replace(/\s*\n\s*/g, '')
          .replace(/ width="16" height="16"/, '')
          .replace(/ class="[^"]*"/, ` class="bi bi-${name}{{ icon_class }}" aria-hidden="true" focusable="false"`);
        writeFileSync(join(target, file), svg);
        names.push(name);
      }
      writeFileSync(join(target, '_names.txt'), `,${names.join(',')},`);
    },
  };
};

// Content hashes of the bundles for cache busting, read by the header and
// the service worker: links change only when a bundle does, not per build
const ASSET_HASH_LENGTH = 10;
const assetVersionsPlugin = () => {
  return {
    name: 'asset-versions',
    // Remove bundles of earlier builds, e.g. leaflet-<old hash>.bundle.js
    buildStart() {
      for (const dir of ['assets/js', 'assets/css']) {
        const path = resolve(import.meta.dirname, dir);
        for (const file of readdirSync(path).filter((file) => file.includes('.bundle.'))) {
          rmSync(join(path, file));
        }
      }
    },
    // Chunks are skipped: imported by name, which carries their hash already
    writeBundle(options, bundle) {
      const lines = ['# Generated by `npm run build`: content hashes of the bundles'];
      const entries = Object.values(bundle).filter((file) => file.type === 'asset' || file.isEntry);
      for (const fileName of entries.map((file) => file.fileName).sort()) {
        const content = readFileSync(join(options.dir, fileName));
        const hash = createHash('sha256').update(content).digest('hex').slice(0, ASSET_HASH_LENGTH);
        lines.push(`${fileName}: "${hash}"`);
      }
      writeFileSync(resolve(import.meta.dirname, '_data/conference_assets.yml'), `${lines.join('\n')}\n`);
    },
  };
};

